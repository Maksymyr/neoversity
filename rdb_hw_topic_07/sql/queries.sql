USE `hw_03`;


-- ------------------------------------------------------------------
-- 1. Рік, місяць і число з атрибута date — трьома окремими стовпчиками.
-- ------------------------------------------------------------------
SELECT
    id,
    `date`,
    YEAR(`date`)  AS order_year,
    MONTH(`date`) AS order_month,
    DAY(`date`)   AS order_day
FROM orders;


-- ------------------------------------------------------------------
-- 2. Додавання одного дня до атрибута date.
-- ------------------------------------------------------------------
SELECT
    id,
    `date`,
    DATE_ADD(`date`, INTERVAL 1 DAY) AS date_plus_one_day
FROM orders;


-- ------------------------------------------------------------------
-- 3. Кількість секунд від початку відліку (Unix timestamp).
-- ------------------------------------------------------------------
SELECT
    id,
    `date`,
    UNIX_TIMESTAMP(`date`) AS date_timestamp
FROM orders;


-- ------------------------------------------------------------------
-- 4. Кількість замовлень із датою в межах
--    від 1996-07-10 00:00:00 до 1996-10-08 00:00:00.
--
--    Стовпчик date зберігається як текст, тому його явно приводимо
--    до типу DATE. Без цього BETWEEN порівнював би рядки посимвольно,
--    і замовлення за 1996-07-10 не потрапили б у результат:
--    рядок '1996-07-10' коротший за '1996-07-10 00:00:00' і тому
--    вважається меншим за нижню межу.
-- ------------------------------------------------------------------
SELECT COUNT(*) AS orders_count
FROM orders
WHERE CAST(`date` AS DATE) BETWEEN '1996-07-10 00:00:00' AND '1996-10-08 00:00:00';


-- ------------------------------------------------------------------
-- 5. JSON-об'єкт {"id": ..., "date": ...} для кожного рядка.
-- ------------------------------------------------------------------
SELECT
    id,
    `date`,
    JSON_OBJECT('id', id, 'date', `date`) AS order_json
FROM orders;
